-- Supabase RLS: access is based on active membership, never client-supplied role metadata.
create or replace function public.is_org_member(target_org bigint)
returns boolean
language sql
stable
security invoker
set search_path = public
as $$
  select exists (
    select 1 from public.organization_memberships m
    where m."organizationId" = target_org
      and m."userId" = (
        select u.id from public.users u
        where lower(u.email) = lower(coalesce((select auth.jwt()->>'email'), ''))
        limit 1
      )
      and m.status = 'active'
  );
$$;

